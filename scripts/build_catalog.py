total = 0
for cat_name, source, items in CATS:
    print(f"\n### {cat_name}   [مرجع: {source}]")
    for name, unit, market, est in items:
        if isinstance(market, tuple) and market[0] == "P":
            p = market[1]
            alo = alo_percent(p)
            mkt_disp = fa_text(f"{p:g}") + "٪"
            alo_disp = fa_text(f"{alo:g}") + "٪"
            mkt_raw, alo_raw = f"{p:g}%", f"{alo:g}%"
        else:
            alo = alo_money(market)
            mkt_disp = fa_money(market)
            alo_disp = fa_money(alo)
            mkt_raw, alo_raw = str(market), str(alo)
        star = " ✱" if est else ""
        print(f"| {name}{star} | {unit} | {mkt_disp} | {alo_disp} |")
        rows_out.append({
            "category": cat_name, "subcategory": name, "unit": unit,
            "market_max": mkt_raw, "alo_rate": alo_raw,
            "estimated": est, "source": source,
        })
        total += 1
print(f"\nTOTAL_ROWS: {total}")

