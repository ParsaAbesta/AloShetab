FA = str.maketrans('0123456789.,', '۰۱۲۳۴۵۶۷۸۹٫٬')

def fa_money(v):
    return f"{v:,}".translate(FA)

def fa_text(s):
    return s.translate(FA)

def alo_money(market):
    step = 1000 if market >= 100000 else 500
    return int(math.floor(market * 0.99 / step) * step)

def alo_percent(p):
    return math.floor(p * 0.99 * 100) / 100.0

